# uat_list_steps <script_name>
# Print the step index out of the STEP_TITLES array the guide script declares.
uat_list_steps() {
    printf 'Steps in %s:\n\n' "$1"
    local index=0
    while [[ $index -lt ${#STEP_TITLES[@]} ]]; do
        printf '  %2s  %s\n' "$index" "${STEP_TITLES[$index]}"
        index=$((index + 1))
    done
}

# uat_resolve_range <last_step>
# Turn --from-step / --only-step into UAT_FIRST_STEP..UAT_LAST_STEP, marking the
# run partial whenever the range is not the whole walkthrough. Also records the
# guide's own extent - UAT_MAX_STEP and UAT_TOTAL_STEPS - which uat_step and
# uat_step_range report against. Exits 2 on a value that is not a step number.
uat_resolve_range() {
    local last="$1"
    UAT_MAX_STEP="$last"
    UAT_TOTAL_STEPS=$((last + 1))
    UAT_FIRST_STEP=0
    UAT_LAST_STEP="$last"
    if [[ -n "$UAT_ONLY_STEP" ]]; then
        uat_require_step_number "--only-step" "$UAT_ONLY_STEP" "$last"
        UAT_FIRST_STEP="$UAT_ONLY_STEP"
        UAT_LAST_STEP="$UAT_ONLY_STEP"
        UAT_PARTIAL=1
    elif [[ -n "$UAT_FROM_STEP" ]]; then
        uat_require_step_number "--from-step" "$UAT_FROM_STEP" "$last"
        UAT_FIRST_STEP="$UAT_FROM_STEP"
        [[ "$UAT_FIRST_STEP" -eq 0 ]] || UAT_PARTIAL=1
    fi
}

# uat_step_range
# The banner's step line, without its label: "0..6 (7 steps)" for a whole
# walkthrough, "3..6 of 0..6" or "3 of 0..6" once a step filter narrowed it. An
# unfiltered run states the guide's extent once rather than printing the same
# range on both sides of an "of". Call uat_resolve_range first.
uat_step_range() {
    if [[ "$UAT_FIRST_STEP" -eq 0 && "$UAT_LAST_STEP" -eq "$UAT_MAX_STEP" ]]; then
        if [[ "$UAT_TOTAL_STEPS" -eq 1 ]]; then
            printf '%s (1 step)\n' "$UAT_FIRST_STEP"
        else
            printf '%s..%s (%s steps)\n' "$UAT_FIRST_STEP" "$UAT_LAST_STEP" "$UAT_TOTAL_STEPS"
        fi
    elif [[ "$UAT_FIRST_STEP" -eq "$UAT_LAST_STEP" ]]; then
        printf '%s of 0..%s\n' "$UAT_FIRST_STEP" "$UAT_MAX_STEP"
    else
        printf '%s..%s of 0..%s\n' "$UAT_FIRST_STEP" "$UAT_LAST_STEP" "$UAT_MAX_STEP"
    fi
}

# uat_run_steps
# Call step_<n> across the resolved range, pausing between steps and honoring
# --stop-on-fail. Call uat_resolve_range first.
uat_run_steps() {
    local index="$UAT_FIRST_STEP" ran_any=0
    while [[ "$index" -le "$UAT_LAST_STEP" ]]; do
        [[ "$ran_any" -eq 0 ]] || uat_pause
        "step_$index"
        ran_any=1
        if [[ "$UAT_STOP_ON_FAIL" -eq 1 && "$UAT_STEP_FAILED" -eq 1 ]]; then
            printf '\n%sstopping at step %s (--stop-on-fail)%s\n' "$UAT_YELLOW" "$index" "$UAT_NC"
            UAT_PARTIAL=1
            break
        fi
        index=$((index + 1))
    done
}

