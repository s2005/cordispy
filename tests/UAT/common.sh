# uat_pause
# Block until a single keypress. Skipped under --auto / UAT_AUTO=1, and whenever
# no terminal is attached, so a piped or redirected run never hangs.
uat_pause() {
    [[ "$UAT_PAUSE" -eq 1 ]] || return 0
    [[ -r /dev/tty ]] || return 0
    printf '\n%sPress any key to continue . . .%s' "$UAT_YELLOW" "$UAT_NC"
    # A closed or non-responding tty makes read fail; that must not be mistaken
    # for a step failure, hence the guard.
    read -rsn 1 </dev/tty || true
    printf '\n'
}

