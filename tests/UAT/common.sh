# uat_summary
# Print the totals and return the script's exit code (0 all passed, 1 otherwise).
#
# A skipped step never changes that exit code - an absent optional tool is not a
# test failure - but it does qualify the RESULT line, so a run that mostly did
# not happen can never be read as a clean pass.
uat_summary() {
    printf '\n'
    printf '====================================================================\n'
    printf '%sSummary%s\n' "$UAT_BOLD" "$UAT_NC"
    printf '  steps run     : %s\n' "$UAT_STEPS_RUN"
    printf '  steps skipped : %s\n' "$UAT_STEPS_SKIPPED"
    printf '  steps failed  : %s\n' "$UAT_STEPS_FAILED"
    printf '  assertions    : %s passed, %s failed\n' "$UAT_PASS_COUNT" "$UAT_FAIL_COUNT"
    if [[ "$UAT_PARTIAL" -eq 1 ]]; then
        printf '  %sPARTIAL RUN%s - a step filter was used, so this is not a full walkthrough\n' \
            "$UAT_YELLOW" "$UAT_NC"
    fi
    if [[ "$UAT_FAIL_COUNT" -eq 0 ]]; then
        if [[ "$UAT_STEPS_SKIPPED" -gt 0 ]]; then
            printf '  %sRESULT: PASS (%s step(s) skipped)%s\n' \
                "$UAT_YELLOW" "$UAT_STEPS_SKIPPED" "$UAT_NC"
        else
            printf '  %sRESULT: PASS%s\n' "$UAT_GREEN" "$UAT_NC"
        fi
        printf '====================================================================\n'
        return "$UAT_EXIT_OK"
    fi
    printf '  %sRESULT: FAIL%s\n' "$UAT_RED" "$UAT_NC"
    printf '====================================================================\n'
    return "$UAT_EXIT_FAIL"
}

